"""forge-core's own index of its governed files, generated from the files themselves.

A document that exists at more than one level is written once at the bottom and generated
above (D-17 §10, A-2). forge-core has no specs of its own: what it governs is the contract,
that is the governed lists and every schema version. ``forge-core/fxts/README.md`` lists
them, built here from the lists and the schema registries, and a test fails when the page
is stale. Nothing in it is typed by hand.

    forge governance index            rewrite the page
    forge governance index --check    exit 1 when the page is stale
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING

from forge_core import contract
from forge_core.fxts.shared import lists, schemas

if TYPE_CHECKING:
    from pathlib import Path

INDEX_PATH = contract.CONTRACT_ROOT.parent / "fxts" / "README.md"


def _short(value: object) -> str:
    return str(value or "")[:12]


def _schema_dirs() -> list[tuple[str, Path]]:
    found = [
        (path.parent.name, path)
        for path in sorted(contract.FXTS_SCHEMAS.glob("*/schema"))
        if (path / schemas.REGISTRY_NAME).is_file()
    ]
    found.append(("lists", lists.SCHEMA_DIR))
    return found


def render() -> str:
    """The page, from the governed lists and the schema registries as they are now."""
    lines = [
        "# forge-core: governed files",
        "",
        "Generated by `forge governance index` from the files it lists. Do not edit.",
        "",
        "forge-core has no specs of its own. What it governs is the contract: the governed",
        "lists and every released schema version, under [`../contract`](../contract). Each",
        "carries a hash, and only the owner approves one.",
        "",
        "## Governed lists",
        "",
        "| List | What it is | Entries | Format | State | Hash | Approved by |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in sorted(lists.ALL_NAMES):
        document = json.loads(lists.list_path(name).read_text(encoding="utf-8"))
        integrity = document.get("integrity", {})
        lines.append(
            f"| [`{name}`](../contract/lists/{name}{lists.SUFFIX}) | {document.get('title', '')} "
            f"| {len(document.get('entries', []))} | {document.get('spec_version', '')} "
            f"| {integrity.get('hash_state', '')} | `{_short(integrity.get('spec_hash'))}` "
            f"| {integrity.get('approved_by') or ''} |"
        )
    lines += [
        "",
        "## Schema versions",
        "",
        "A released version is never edited; a change is a new version. `*` marks the current",
        "one.",
        "",
        "| Schema | Version | Step | State | Hash | Approved by |",
        "|---|---|---|---|---|---|",
    ]
    for framework, schema_dir in _schema_dirs():
        head = schemas.latest(schema_dir)
        for row in schemas.versions(schema_dir):
            current = "*" if head is not None and row.version == head.version else ""
            lines.append(
                f"| {framework} | {row.version}{current} | {row.step} | {row.hash_state} "
                f"| `{_short(row.schema_hash)}` | {row.approved_by or ''} |"
            )
    return "\n".join(lines) + "\n"


def is_current() -> bool:
    return INDEX_PATH.is_file() and INDEX_PATH.read_text(encoding="utf-8") == render()


def write() -> bool:
    """Rewrite the page. True when it changed."""
    changed = not is_current()
    INDEX_PATH.parent.mkdir(parents=True, exist_ok=True)
    INDEX_PATH.write_text(render(), encoding="utf-8")
    return changed
